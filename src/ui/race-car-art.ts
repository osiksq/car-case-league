export function useCarImage(element: HTMLImageElement | null) {
  let sprite: HTMLCanvasElement | undefined;
  const contour = silhouetteProfiles[Number(element?.dataset.artIndex)];
  return () => {
    if (sprite || !contour || !element?.complete || !element.naturalWidth) return sprite;
    // Clip the existing studio artwork for the track, keeping the original file and car livery.
    const canvas = document.createElement('canvas');
    canvas.width = element.naturalWidth;
    canvas.height = element.naturalHeight;
    const context = canvas.getContext('2d');
    if (!context) return undefined;
    context.beginPath();
    for (let index = 0; index < contour.length; index += 2) {
      const x = contour[index] / 100 * canvas.width;
      const y = contour[index + 1] / 100 * canvas.height;
      if (index === 0) context.moveTo(x, y);
      else context.lineTo(x, y);
    }
    context.closePath();
    context.clip();
    context.drawImage(element, 0, 0);
    sprite = canvas;
    return sprite;
  };
}
